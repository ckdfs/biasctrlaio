#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENV_DIR="${ROOT_DIR}/.venv"
TOOLCHAIN_DIR="${ROOT_DIR}/.toolchain"
SDK_DIR="${TOOLCHAIN_DIR}/zephyr-sdk"
BRIDGE_TMP="${ROOT_DIR}/.agent-bridge/tmp"
ENV_FILE="${ROOT_DIR}/scripts/env.sh"

mkdir -p "${BRIDGE_TMP}"
export TMPDIR="${BRIDGE_TMP}"

require_cmd() {
    local cmd="$1"
    local hint="$2"
    if ! command -v "${cmd}" >/dev/null 2>&1; then
        echo "ERROR: Missing required tool '${cmd}'. ${hint}" >&2
        exit 1
    fi
}

require_cmd "uv" "Install uv: https://docs.astral.sh/uv/getting-started/installation/"
require_cmd "cmake" "On macOS run: brew bundle --file=${ROOT_DIR}/Brewfile"
require_cmd "ninja" "On macOS run: brew bundle --file=${ROOT_DIR}/Brewfile"
require_cmd "dtc" "On macOS run: brew bundle --file=${ROOT_DIR}/Brewfile"

if [[ ! -d "${VENV_DIR}" ]]; then
    echo "==> Creating Python virtual environment in .venv"
    uv venv "${VENV_DIR}"
fi

echo "==> Installing base Python tooling (west, pyocd, pytest)"
uv pip install --python "${VENV_DIR}/bin/python" west pyocd pytest

if [[ ! -d "${ROOT_DIR}/.west" ]]; then
    echo "==> Initializing west workspace inside ${ROOT_DIR}"
    "${VENV_DIR}/bin/west" init -l "${ROOT_DIR}/manifest"
fi

echo "==> Updating Zephyr modules (shallow narrow fetch)"
(cd "${ROOT_DIR}" && "${VENV_DIR}/bin/west" update --narrow -o=--depth=1)

echo "==> Installing Zephyr Python dependencies"
uv pip install --python "${VENV_DIR}/bin/python" -r "${ROOT_DIR}/deps/zephyr/scripts/requirements-base.txt"

find_arm_gcc() {
    for candidate in \
        "${SDK_DIR}/gnu/arm-zephyr-eabi/bin/arm-zephyr-eabi-gcc" \
        "${SDK_DIR}/arm-zephyr-eabi/bin/arm-zephyr-eabi-gcc"; do
        if [[ -x "${candidate}" ]]; then
            echo "${candidate}"
            return 0
        fi
    done
    return 1
}

if ! find_arm_gcc >/dev/null 2>&1; then
    echo "==> Installing minimal Zephyr SDK (arm-zephyr-eabi) into ${SDK_DIR}"
    mkdir -p "${TOOLCHAIN_DIR}"
    PAT_ARGS=()
    TOKEN="${GITHUB_TOKEN:-${GH_TOKEN:-}}"
    if [[ -z "${TOKEN}" ]] && command -v gh >/dev/null 2>&1; then
        TOKEN="$(gh auth token 2>/dev/null || true)"
    fi
    if [[ -n "${TOKEN}" ]]; then
        PAT_ARGS=(--personal-access-token "${TOKEN}")
    fi
    (cd "${ROOT_DIR}" && ZEPHYR_BASE="${ROOT_DIR}/deps/zephyr" "${VENV_DIR}/bin/west" sdk install -d "${SDK_DIR}" -t arm-zephyr-eabi -H "${PAT_ARGS[@]}")
else
    echo "==> Zephyr SDK already present at ${SDK_DIR}"
fi

ARM_GCC_PATH="$(find_arm_gcc || true)"
if [[ -z "${ARM_GCC_PATH}" ]]; then
    echo "ERROR: Zephyr SDK installation failed; arm-zephyr-eabi-gcc not found under ${SDK_DIR}" >&2
    exit 1
fi
ARM_BIN_DIR="$(dirname "${ARM_GCC_PATH}")"

cat > "${ENV_FILE}" <<EOF
# Generated by scripts/bootstrap.sh — do not edit manually
export BIASCTRLAIO_ROOT="${ROOT_DIR}"
export ZEPHYR_BASE="${ROOT_DIR}/deps/zephyr"
export ZEPHYR_SDK_INSTALL_DIR="${SDK_DIR}"
export ZEPHYR_TOOLCHAIN_VARIANT="zephyr"
export TMPDIR="${BRIDGE_TMP}"
case ":\${PATH}:" in
  *":${VENV_DIR}/bin:"*) ;;
  *) export PATH="${VENV_DIR}/bin:\${PATH}" ;;
esac
case ":\${PATH}:" in
  *":${ARM_BIN_DIR}:"*) ;;
  *) export PATH="${ARM_BIN_DIR}:\${PATH}" ;;
esac
EOF

echo "==> Generating scripts/env.sh complete."
echo "Run: source ${ENV_FILE}"
