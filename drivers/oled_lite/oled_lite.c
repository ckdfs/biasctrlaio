static unsigned char uppercase(unsigned char c)
{
	return c >= 'a' && c <= 'z' ? c - 'a' + 'A' : c;
}

static bool is_supported_char(unsigned char c)
{
	return (c >= '0' && c <= '9') || (c >= 'A' && c <= 'Z') ||
	       c == ' ' || c == '-' || c == '.' || c == ':';
}

int oled_lite_text(unsigned int x, unsigned int y, const char *text)
{
	if (!text) {
		return -EINVAL;
	}
	if (x > WIDTH || y > HEIGHT - 8U || strlen(text) > (WIDTH - x) / 6U) {
		return -ERANGE;
	}
	for (const char *p = text; *p; ++p) {
		if (!is_supported_char(uppercase((unsigned char)*p))) {
			return -ENOTSUP;
		}
	}
	k_mutex_lock(&bias_i2c1_mutex, K_FOREVER);
	for (; *text; ++text, x += 6U) {
		const uint8_t *rows = glyphs[uppercase((unsigned char)*text) - ' '];
		for (unsigned int row = 0; row < 8U; ++row) {
			for (unsigned int col = 0; col < 6U; ++col) {
				pixel(x + col, y + row, row < 7U && col < 5U &&
				      (rows[row] & BIT(4U - col)));
			}
		}
	}
	k_mutex_unlock(&bias_i2c1_mutex);
	return 0;
}

/* SSD1306 horizontal addressing. Keep the control byte and its data in
 * one I2C write, including on controllers that cannot concatenate messages.
 */
static int flush_locked(void)
{
	static const uint8_t window[] = { 0, 0x21, 0, WIDTH - 1, 0x22, 0, HEIGHT / 8 - 1 };
	uint8_t packet[1 + WIDTH] = { 0x40 };
	int rc = i2c_write(bus, window, sizeof(window), OLED_ADDR);

	for (size_t page = 0; !rc && page < ARRAY_SIZE(framebuffer); ++page) {
		memcpy(packet + 1, framebuffer[page], WIDTH);
		rc = i2c_write(bus, packet, sizeof(packet), OLED_ADDR);
	}
	return rc;
}

int oled_lite_flush(void)
{
	if (!device_is_ready(bus)) {
		return -ENODEV;
	}
	k_mutex_lock(&bias_i2c1_mutex, K_FOREVER);
	int rc = flush_locked();
	k_mutex_unlock(&bias_i2c1_mutex);
	return rc;
}

int oled_lite_init(void)
{
	static const uint8_t setup[] = {
		0, 0xae, 0xd5, 0x80, 0xa8, HEIGHT - 1, 0xd3, 0, 0x40,
		0x8d, 0x14, 0x20, 0, 0xa1, 0xc8, 0xda, 0x12,
		0x81, 0x7f, 0xd9, 0xf1, 0xdb, 0x40, 0xa4, 0xa6,
	};
	static const uint8_t display_on[] = { 0, 0xaf };

	if (!device_is_ready(bus)) {
		return -ENODEV;
	}
	k_mutex_lock(&bias_i2c1_mutex, K_FOREVER);
	int rc = i2c_write(bus, setup, sizeof(setup), OLED_ADDR);
	if (!rc) {
		memset(framebuffer, 0, sizeof(framebuffer));
		rc = flush_locked();
	}
	if (!rc) {
		rc = i2c_write(bus, display_on, sizeof(display_on), OLED_ADDR);
	}
	k_mutex_unlock(&bias_i2c1_mutex);
	return rc;
}
