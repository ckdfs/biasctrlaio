#define WIDTH 128U
#define HEIGHT 64U
#define OLED_ADDR 0x3c
static const struct device *const bus = DEVICE_DT_GET(DT_NODELABEL(i2c1));
static uint8_t framebuffer[HEIGHT / 8][WIDTH];
BUILD_ASSERT(sizeof(framebuffer) <= 1024);

static void pixel(unsigned int x, unsigned int y, bool on)
{
	uint8_t *byte = &framebuffer[y / 8][x];
	WRITE_BIT(*byte, y % 8, on);
}

void oled_lite_clear(void)
{
	k_mutex_lock(&bias_i2c1_mutex, K_FOREVER);
	memset(framebuffer, 0, sizeof(framebuffer));
	k_mutex_unlock(&bias_i2c1_mutex);
}

int oled_lite_pixel(unsigned int x, unsigned int y, bool on)
{
	if (x >= WIDTH || y >= HEIGHT) {
		return -ERANGE;
	}
	k_mutex_lock(&bias_i2c1_mutex, K_FOREVER);
	pixel(x, y, on);
	k_mutex_unlock(&bias_i2c1_mutex);
	return 0;
}

